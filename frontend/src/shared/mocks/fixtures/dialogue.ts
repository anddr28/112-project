/**
 * FIXTURE: разговор с заявителем.
 *
 * Здесь нет ни распознавания речи, ни языковой модели — их место занимает
 * детерминированная таблица «ключевые слова → реплика заявителя». Этого
 * достаточно, чтобы собрать и проверить интерфейс разговора до появления
 * ai-service, и невозможно перепутать с настоящей реализацией.
 *
 * Когда появится backend (`POST /attempts/{id}/dialogue/turns`), файл
 * удаляется вместе со всем mock-слоем.
 *
 * Бриф и чек-лист — преподавательские данные: обучающемуся не отдаются
 * (см. mockApi.callScript.get и mockApi.dialogue.*).
 */

import type { DialogueBrief, ExpectedDialogue } from '../../types';

/** Правило ответа: какие слова ищем в реплике оператора и что отвечаем. */
export interface CallerRule {
  /** подстроки в нижнем регистре; достаточно одного совпадения */
  match: string[];
  reply: string;
  /** факт брифа, который раскрывается этим ответом */
  revealsFactId?: string;
  emotionalState?: string;
  /** ответ завершает разговор */
  endsCall?: boolean;
}

