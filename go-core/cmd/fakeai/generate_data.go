type factTpl struct {
	id      string
	text    string
	reveal  components.DialogueFactReveal
	hints   []string
	minDiff int
	desc    string // предложение для описания эталонной карточки (если факт в сценарии)
}

type itemTpl struct {
	id       string
	text     string
	kind     components.DialogueChecklistItemKind
	required bool
	weight   float32
	hints    []string
}

type roleTpl struct {
	role   string
	female bool
}

type sceneTpl struct {
	kind      string
	codes     []string // коды категорий классификатора
	match     []string // основы слов в названии/пути категории
	titles    []string
	indoor    bool // квартира/подъезд/этаж
	landmark  string
	where     string // откуда звонит (для persona)
	roles     []roleTpl
	opening   string
	facts     []factTpl
	never     string
	unknowns  []string
	fallback  []string
	desc      string // начало описания эталонной карточки
	actions   string
	injured   int
	trapped   int
	services  []string
	what      itemTpl
	safety    *itemTpl
	expected  string
	expFacts  []string
	forbidden []string
}

type addrTpl struct {
	street     string // как в поле street (фикстуры фронта: «Тверская», «Ленинский проспект»)
	streetFull string // как в raw
	house      string
	corp       string
}

