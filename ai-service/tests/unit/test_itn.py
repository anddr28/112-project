import pytest

from ai_service.engines.stt.itn_ru import itn


@pytest.mark.parametrize(("src", "want"), [
    ("улица Ленина дом четырнадцать подъезд три", "улица Ленина дом 14 подъезд 3"),
    ("Служба сто двенадцать, слушаю.", "Служба 112, слушаю."),
    ("пятый этаж, квартира двадцать семь", "5 этаж, квартира 27"),
    ("Третий подъезд, пятый этаж!", "3 подъезд, 5 этаж!"),
    ("двадцать пятый этаж", "25 этаж"),
    ("восемь девятьсот шестнадцать сто двадцать три сорок пять шестьдесят семь", "8 916 123 45 67"),
    ("две тысячи двадцать четыре", "2024"),
    ("тысяча", "1000"),
    ("корпус один", "корпус 1"),
    ("одна женщина, второй раз звоню", "одна женщина, второй раз звоню"),
    ("Пострадавших двое? Нет, трое.", "Пострадавших двое? Нет, трое."),
    ("", ""),
])
def test_itn(src, want):
    assert itn(src) == want
