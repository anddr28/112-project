-- от оператора 112, и статусы реагирования он проставляет только своей службе. Служба
-- фиксируется при выдаче карточки (как etalon_id): профиль обучающегося
-- (users.service_id) могут поменять посреди занятия, а оценка и права на статусы
-- должны остаться объяснимыми задним числом. У попыток ракурса 112 — NULL.
